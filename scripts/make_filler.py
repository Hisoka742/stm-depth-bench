"""Нейтральный банковский наполнитель для эксперимента с длиной контекста.

    python scripts/make_filler.py --model deepseek/deepseek-v4-pro

Языковая модель пишет короткие обмены репликами клиента и ассистента банка на общие темы
(карты, вклады, безопасность, приложение и т. д.). Затем обмены фильтруются: отбрасываются
все, где есть цифры, названия месяцев, денежные единицы, адреса, слова из названий слотов
бенчмарка и названия сущностей (члены семьи, продукты, виды расходов), чтобы наполнитель не
содержал значений и упоминаний, которые можно спутать с цепочкой. Результат — data/filler_bank.jsonl
(вопрос клиента, ответ ассистента, тема); порядок фиксирован, и наборы с длинным контекстом
берут из него обмены по порядку.
"""
from __future__ import annotations

import argparse
import json
import os
import re
import sys
from concurrent.futures import ThreadPoolExecutor

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from stmbench.openrouter import NO_REASONING, chat  # noqa: E402

THEMES = [
    "дебетовые карты: оформление, перевыпуск, дизайн, бесконтактная оплата",
    "вклады и накопительные счета: условия, пополнение, досрочное закрытие",
    "кредиты: оформление, досрочное погашение, кредитная история",
    "безопасность: мошенники, коды из сообщений, подозрительные звонки",
    "мобильное приложение: вход, настройки, уведомления, обновления",
    "валютные операции и поездки за границу",
    "страхование: какие бывают полисы, как оформить через банк",
    "инвестиции для начинающих: брокерский счёт, риски, налоги",
    "отделения и банкоматы: режим работы, очереди, электронная очередь",
    "кэшбэк и бонусные программы",
    "документы и справки: выписки, справки для визы, налоговые документы",
    "счета для самозанятых и малого бизнеса",
    "пенсионные продукты и обслуживание пенсионеров",
    "детские карты и финансовая грамотность подростков",
    "оспаривание операций и ошибочные списания",
    "система быстрых платежей и межбанковские переводы",
    "автоплатежи и подписки: как подключить и отключить",
    "закрытие счёта и смена банка",
    "ипотека: общие вопросы, страхование, рефинансирование",
    "сейфовые ячейки и хранение ценностей",
    "персональные данные: смена паспорта, фамилии, кодового слова",
    "лимиты на операции и блокировки по подозрению на мошенничество",
    "цифровой рубль, электронные кошельки и платёжные стикеры",
    "благотворительность и регулярные пожертвования через банк",
]

SYSTEM = (
    "Ты пишешь реплики для синтетических диалогов клиента с ассистентом банка. Каждый обмен — "
    "один вопрос клиента и ответ ассистента в 2–4 предложения, вежливый и правдоподобный. Нельзя: "
    "цифры и числа (даже словами), даты, названия месяцев, суммы денег и денежные единицы, адреса и "
    "названия улиц, номера телефонов и карт, время суток с часами, имена людей и родственников, названия "
    "конкретных банков. Вопросы должны быть разными и не повторяться. Верни только JSON-массив "
    "объектов вида {\"q\": \"...\", \"a\": \"...\"}."
)

BAN = re.compile(
    r"\d|январ|феврал|март|апрел|\bма[йя]\b|июн|июл|август|сентябр|октябр|ноябр|декабр|рубл|₽|доллар|евро|"
    r"\bул\.|улиц|проспект|переул|телефон|номер|адрес|дата|сумм|время|час|минут|утр|вечер|"
    r"мам|пап|брат|сестр|сын|доч|отец|отц|бабуш|дедуш|муж|жен[аеуы]\b|"
    r"аренд|детск\w* сад|обучен|путёвк|путевк|курс\w* английск|ремонт машин|"
    r"мобильн\w* связ|интернет|коммунальн|парковк|такси|"
    r"ноль|один|одна|два|две|три|четыр|пять|шест|сем[ьи]|восем|девят|десят|сорок|сто\b|тысяч|миллион|"
    r"перв|втор|трет|половин|четверт|сутк|недел|год|месяц",
    re.IGNORECASE)


def batch(model, theme, k):
    msgs = [{"role": "system", "content": SYSTEM},
            {"role": "user", "content": f"Тема: {theme}. Напиши {k} разных обменов."}]
    r = chat(model, msgs, temperature=0.7, max_tokens=8000, extra=NO_REASONING)
    m = re.search(r"\[.*\]", r["content"], re.S)
    try:
        items = json.loads(m.group(0)) if m else []
    except json.JSONDecodeError:
        items = []
    return [dict(q=x.get("q", "").strip(), a=x.get("a", "").strip(), theme=theme) for x in items
            if isinstance(x, dict)], (r.get("usage") or {}).get("cost") or 0


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--model", default="deepseek/deepseek-v4-pro")
    ap.add_argument("--per-theme", type=int, default=40)
    ap.add_argument("--rounds", type=int, default=2)
    ap.add_argument("--append", action="store_true", help="дописать к уже готовому наполнителю")
    args = ap.parse_args()
    jobs = [t for t in THEMES for _ in range(args.rounds)]
    with ThreadPoolExecutor(6) as ex:
        res = list(ex.map(lambda t: batch(args.model, t, args.per_theme), jobs))
    cost = sum(c for _, c in res)
    raw = [x for items, _ in res for x in items]
    out = os.path.join(ROOT, "data", "filler_bank.jsonl")
    old = []
    if args.append and os.path.exists(out):
        with open(out, encoding="utf-8") as f:
            old = [json.loads(x) for x in f if x.strip()]
    seen = {re.sub(r"\W+", " ", x["q"].lower()).strip() for x in old}
    keep, dropped = list(old), 0
    for x in raw:
        key = re.sub(r"\W+", " ", x["q"].lower()).strip()
        if not x["q"] or not x["a"] or key in seen or BAN.search(x["q"] + " " + x["a"]):
            dropped += 1
            continue
        seen.add(key)
        keep.append(x)
    with open(out, "w", encoding="utf-8") as f:
        for x in keep:
            f.write(json.dumps(x, ensure_ascii=False) + "\n")
    print(f"получено {len(raw)}, всего в наполнителе {len(keep)}, отброшено {dropped}; стоимость {cost:.3f} $; {out}")


if __name__ == "__main__":
    main()
