@dataclass
class Domain:
    key: str
    title: str
    vtype: str
    gender: str              # род главного слова названия слота
    slot_nom: str
    slot_acc: str
    entities: list[dict]
    intro_user: str          # {list}
    list_form: str           # какая форма сущности идёт в перечисление
    intro_agent: str
    reasons: list            # строки или (строка, ограничение) для упорядоченных типов
    corr_reasons: list[str]
    first_user: list[str]
    explicit_user: list[str]
    implicit_user: list[str]
    correction_user: list[str]
    rejected_user: str
    action_user: str         # просьба выполнить действие со значением (ложная предпосылка)
    stray_user: list[str]
    forget_tail: str
    filler: list[tuple[str, str]]
    stray_entity: list[str] = field(default_factory=list)   # упоминания рядом с названием сущности
    ellipsis_agent: str = ""                                 # запись в два хода: вопрос агента
    ellipsis_user: str = "{new}."                            # и короткий ответ пользователя
    resolves: dict | None = None  # группы причин, снимающие предыдущую причину при смене направления
    corr_adjacent: list = field(default_factory=list)  # причины исправления на соседнее значение

    def corr_pool(self, kind: str) -> list[str]:
        return list(self.corr_reasons) + CORR_BY_KIND.get(kind, []) + (self.corr_adjacent if kind == "adjacent" else [])
    intro_one: str = ""      # вводная реплика, если сущность одна (m = 0)
    intro_agent_one: str = ""  # ответ ассистента на неё

    @property
    def vt(self):
        return TYPES[self.vtype]

    @property
    def value_regex(self) -> str:
        return self.vt.regex

    def reason_list(self) -> list[tuple[str, dict | None]]:
        return [r if isinstance(r, tuple) else (r, None) for r in self.reasons]

    def sample_values(self, rng: random.Random, k: int, exclude: set) -> list[str]:
        out: list[str] = []
        seen = set(exclude)
        for _ in range(100000):
            v = self.vt.sample(rng)
            c = self.vt.canon(v)
            if c in seen:
                continue
            seen.add(c)
            out.append(v)
            if len(out) == k:
                return out
        raise RuntimeError("не хватает значений")


