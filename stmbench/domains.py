"""Предметные области сценариев: клиент общается с ассистентом банка.

В каждой области есть несколько однотипных слотов (по одному на «сущность»: карту для члена
семьи, платёж, получателя перевода, банковский продукт, тему звонка, вид расходов). Один из
слотов целевой, остальные используются как однотипные помехи (параметр m). Во вводной реплике
всегда сказано, что у каждой сущности ровно одно значение слота: на этом держится однозначность
неявных обновлений (п. 2.1.2 ВКР).

Причины изменений согласованы со значениями: для упорядоченных типов (дата, сумма, время)
каждая причина задаёт направление изменения, а для времени — ещё и интервалы, в которых
должны лежать прежнее и новое значение (stmbench/values.py). Исправление ошибки всегда даёт
близкое значение: перепутанные цифры, соседний номер дома, соседний день.

Плейсхолдеры шаблонов:
  {slot}/{Slot}   — полное название слота («адрес доставки карты для мамы»);
  {slot_acc}      — оно же в винительном падеже («сумму перевода брату»);
  {q}, {E}, {E_gen}, {E_dat}, {E_acc} — формы названия сущности;
  {v}, {old}, {new}, {w}, {cur}, {x} — значения слота;
  {reason}/{Reason} — описание события (причины изменения);
  [мужская|женская] — форма, зависящая от рода пользователя.
"""
