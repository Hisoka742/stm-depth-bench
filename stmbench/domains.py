"""Предметные области сценариев.

В каждой области есть несколько однотипных слотов (по одному на «сущность»: получателя
подарка, встречу, комнату, работника, пункт плана, часть отчёта). Один из слотов целевой,
остальные используются как однотипные помехи (параметр m). Во вводной реплике всегда
сказано, что у каждой сущности ровно одно значение слота: на этом держится однозначность
неявных обновлений (п. 2.1.2 ВКР).

Плейсхолдеры шаблонов:
  {slot}/{Slot}   — полное название слота («адрес доставки для мамы»);
  {slot_acc}      — оно же в винительном падеже («дату встречи с юристом»);
  {E}, {E_gen}, {E_dat}, {E_acc}, {E_loc} — формы названия сущности;
  {v}, {old}, {new}, {w}, {cur}, {x} — значения слота;
  {reason}/{Reason} — описание события (причины изменения);
  [мужская|женская] — форма, зависящая от рода пользователя.
"""
