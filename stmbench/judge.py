"""LLM-судья — запасной шаг проверки (п. 2.4 ВКР).

Судья вызывается только для ответов, из которых код не смог однозначно извлечь значение
(значений нет или их несколько). Судья не сравнивает ответ с эталоном и не видит значений
из диалога: он только выписывает значение, которое модель дала как ответ, в каноническом
формате типа слота, либо сообщает, что ответ — отказ, что значения нет или что модель
назвала несколько значений и не выбрала одно. Сравнение выписанного значения с эталоном
выполняет код (scoring.py), поэтому судья не может «притянуть» близкое значение к эталону.
"""
from __future__ import annotations

import json
import re

from .scoring import label_of
from .values import TYPES

FORMAT = {
    "addr": "ул. Садовая, 12",
    "date": "12 декабря",
    "money": "260 000 рублей",
    "phone": "+7 912 345-67-89",
    "time": "9:30",
    "card": "*4821",
}

JUDGE_SYSTEM = (
    "Ты помогаешь проверять ответы диалоговой модели. Тебе даны вопрос пользователя и ответ модели. "
    "Выпиши значение, которое модель дала в качестве ответа на вопрос, и запиши его в формате "
    "из примера. Сохраняй все цифры такими, как они написаны в ответе, ничего не исправляй и не "
    "дополняй; если значение в ответе неполное или оборвано, выпиши его как есть. Если модель называет "
    "несколько значений и нельзя понять, какое из них она считает ответом, верни MULTIPLE. Если модель "
    "отказывается отвечать или сообщает, что данных нет (в том числе ответ «нет данных»), верни REFUSAL. "
    "Если модель отвечает, но значения в ответе нет, "
    "верни NONE. Верни только JSON вида {\"value\": \"...\"}."
)


def judge_prompt(s: dict, q: dict, answer: str, seed: int = 0) -> tuple[list[dict], dict]:
    user = (f"Слот: {s['slot']}\nФормат значения: {FORMAT[s['vtype']]}\n"
            f"Вопрос пользователя: {q['text']}\nОтвет модели: {answer}")
    return [{"role": "system", "content": JUDGE_SYSTEM}, {"role": "user", "content": user}], {"s": s}


def parse_judge(text: str, mapping: dict) -> str:
    """Метка по ответу судьи: значение сопоставляется со значениями из входа кодом."""
    s = mapping["s"]
    val = None
    m = re.search(r"\{.*?\}", text, re.S)
    if m:
        try:
            val = json.loads(m.group(0)).get("value")
        except json.JSONDecodeError:
            val = None
    if val is None:
        val = text.strip()
    val = str(val).strip()
    if val.upper() in ("MULTIPLE", "REFUSAL", "NONE"):
        return val.upper()
    labs = label_of(TYPES[s["vtype"]].extract(val), s)
    if len(labs) == 1:
        return labs[0]
    return "NONE" if not labs else "MULTIPLE"
