def ordinal_instr(j: int, gender: str) -> str:
    """Порядковое числительное в творительном падеже: «вторым» / «второй»."""
    return (ORD_INSTR_F if gender == "f" else ORD_INSTR_M)[j - 1]


_GENDER_RE = re.compile(r"\[([^\[\]|]*)\|([^\[\]|]*)\]")


def resolve_gender(text: str, user_gender: str) -> str:
    """Заменяет конструкции [мужская|женская] формой, соответствующей роду пользователя."""
    idx = 1 if user_gender == "m" else 2
    return _GENDER_RE.sub(lambda m: m.group(idx), text)


def cap(s: str) -> str:
    return s[:1].upper() + s[1:] if s else s


def join_ru(items: list[str]) -> str:
    """«а, б и в»."""
    if len(items) == 1:
        return items[0]
    return ", ".join(items[:-1]) + " и " + items[-1]
